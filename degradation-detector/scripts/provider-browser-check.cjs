'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { createPreview } = require('./provider-preview.cjs');
let playwright;
try { playwright = require(process.env.PLAYWRIGHT_MODULE || 'playwright'); }
catch { playwright = require(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')); }

async function main() {
  let preview = await createPreview(0);
  const menuServer = http.createServer((_req, res) => {
    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.end(`<!doctype html><html><body style="margin:0"><iframe id="detector" src="${preview.baseUrl}/results?demo=readonly" style="width:100%;height:900px;border:0" title="检测结果"></iframe></body></html>`);
  });
  await new Promise(resolve => menuServer.listen(0, '127.0.0.1', resolve));
  const menuUrl = `http://127.0.0.1:${menuServer.address().port}`;
  let browser;
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'sub2api-provider-browser-'));
  const errors = [];
  const external = [];
  const watch = page => {
    page.setDefaultTimeout(12000);
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/^https?:/.test(request.url()) && ![preview.baseUrl, menuUrl].some(base => request.url().startsWith(base + '/'))) external.push(request.url()); });
  };
  const fit = async page => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'page must fit viewport');
  const shot = (page, name) => page.screenshot({ path: path.join(directory, `${name}.png`), fullPage: true });
  const save = async page => {
    const response = page.waitForResponse(response => new URL(response.url()).pathname === '/api/admin/provider-config' && response.request().method() === 'PUT');
    await page.locator('#pc-save').click();
    const result = await response;
    assert.equal(result.status(), 200, await result.text());
    await page.waitForFunction(() => document.getElementById('pc-save-label').textContent === '保存三方配置');
    return result.json();
  };
  try {
    browser = await playwright.chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
    for (const layout of [{ name: 'desktop', width: 1440, dark: false }, { name: 'mobile', width: 390, dark: false }, { name: 'narrow', width: 320, dark: false }, { name: 'dark', width: 1440, dark: true }]) {
      if (layout.name !== 'desktop') { await preview.close(); preview = await createPreview(0); }
      const context = await browser.newContext({ viewport: { width: layout.width, height: 900 }, colorScheme: layout.dark ? 'dark' : 'light', locale: 'zh-CN' });
      const page = await context.newPage(); watch(page);
      await page.goto(`${preview.baseUrl}/results?demo=readonly`);
      await page.locator('.p-card').first().waitFor();
      assert.equal(await page.locator('.p-card').count(), 3);
      assert.equal(await page.locator('.p-card').first().locator('.p-bar').count(), 24);
      assert.equal(await page.locator('.p-bar.passed').first().evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(53, 184, 135)');
      await fit(page); await shot(page, `${layout.name}-candy`);
      await page.locator('#p-search').fill('官Key');
      assert.equal(await page.locator('.p-card').count(), 1);
      await page.locator('#p-search').fill('');
      await page.locator('#p-status').selectOption('failed');
      assert.equal(await page.locator('.p-card').count(), 0);
      await page.locator('#p-status').selectOption('');
      const pelicanResponse = page.waitForResponse(response => response.url().includes('/api/provider-results?channel=pelican'));
      await page.locator('[data-channel="pelican"]').click();
      await pelicanResponse;
      await page.locator('.p-card button[data-group="8"]').last().click();
      await page.locator('.p-artwork').waitFor();
      await page.frameLocator('.p-artwork').locator('svg').waitFor();
      assert.equal(await page.locator('.p-artwork').getAttribute('sandbox'), 'allow-scripts');
      await page.locator('.p-history-detail summary').filter({ hasText: '作品源码' }).click();
      assert.match(await page.locator('.p-history-detail').innerText(), /<!doctype html>/);
      await fit(page); await shot(page, `${layout.name}-pelican-detail`);
      await page.locator('[data-history-close]').click();
      await page.locator('[data-provider="testllm"]').click();
      await page.locator('.p-table tbody tr').first().waitFor();
      assert.equal(await page.locator('.p-table tbody tr').count(), 2);
      assert.match(await page.locator('.p-table').first().innerText(), /极高智商/);
      await fit(page); await shot(page, `${layout.name}-testllm`);
      await page.locator('.p-table').first().getByRole('button', { name: '24小时检测记录' }).click();
      await page.locator('.p-history-detail summary').first().waitFor();
      assert.equal(await page.locator('.p-history-list [data-run-id]').count(), 24);
      assert.match(await page.locator('.p-history-detail').innerText(), /首字耗时：未取得/);
      await fit(page); await shot(page, `${layout.name}-testllm-detail`);
      if (layout.name === 'desktop') {
        preview.runtime.store.db.prepare("UPDATE degradation_provider_groups SET enabled=0 WHERE group_id='8' AND channel='testllm'").run();
        await page.evaluate(() => document.getElementById('refresh-button').click());
        await page.waitForFunction(() => !document.querySelector('.p-history').open);
        assert.equal(await page.locator('.p-history-detail').innerText(), '');
        preview.runtime.store.db.prepare("UPDATE degradation_provider_groups SET enabled=1 WHERE group_id='8' AND channel='testllm'").run();
      } else await page.locator('[data-history-close]').click();
      const denied = await page.evaluate(async () => {
        const targets = ['/admin/config', '/admin/provider-config.js', '/api/admin/provider-config'];
        return Promise.all(targets.map(url => fetch(url).then(response => response.status)));
      });
      assert.deepEqual(denied, [403, 403, 403]);
      await context.close();

      const adminContext = await browser.newContext({ viewport: { width: layout.width, height: 900 }, colorScheme: layout.dark ? 'dark' : 'light', locale: 'zh-CN' });
      const admin = await adminContext.newPage(); watch(admin);
      await admin.goto(`${preview.baseUrl}/admin/config?demo=1`);
      await admin.locator('#pc-provider-form').waitFor();
      assert.equal(await admin.locator('#legacy-config').evaluate(element => element.open), false);
      assert.equal(await admin.locator('[data-pc-site]').count(), 2);
      assert.equal(await admin.locator('[data-pc-site="manxue"] [name="api_url"]').count(), 1);
      assert(await admin.locator('.pc-main-tabs').evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'main configuration tabs must fit');
      await fit(admin); await shot(admin, `${layout.name}-admin-providers`);
      const store = preview.runtime.providerStore;
      const claudeKey = store.group('2', 'candy').key_cipher;
      await admin.locator('[data-pc-view="platforms"]').click();
      await admin.locator('[data-pc-platform="openai"]').click();
      assert.equal(await admin.locator('[data-pc-unify]').isVisible(), true, 'legacy category defaults also need an explicit unification action');
      const preserved = await save(admin);
      assert.deepEqual(preserved.platforms, [], 'merely opening and saving must retain legacy category defaults');
      assert.equal(store.group('2', 'candy').key_cipher, claudeKey);
      await admin.locator('[data-pc-unify]').click();
      assert.equal(await admin.locator('[data-pc-unify]').count(), 0);
      assert(await admin.locator('#pc-history-channel').evaluate(element => {
        const style = getComputedStyle(element);
        const context = document.createElement('canvas').getContext('2d');
        context.font = `${style.fontSize} ${style.fontFamily}`;
        const text = Math.max(...[...element.options].map(option => context.measureText(option.text).width));
        return element.clientWidth >= text + parseFloat(style.paddingLeft) + parseFloat(style.paddingRight) + 18;
      }), 'category selection must remain readable');
      const form = admin.locator('#pc-platform-form');
      const preset = form.locator('[name="reasoning_effort_preset"]');
      const custom = form.locator('[name="reasoning_effort"]');
      assert.equal(await form.locator('[name="model"]').count(), 1);
      assert.deepEqual(await preset.locator('option').evaluateAll(options => options.map(option => option.value)), ['low', 'medium', 'high', 'xhigh', 'max', 'ultra', 'custom']);
      await form.locator('[name="model"]').fill(`gpt-shared-${layout.name}`);
      await form.locator('[name="target_url"]').fill('https://gpt-relay.example.com/v1');
      await preset.selectOption('ultra');
      assert.equal(await custom.inputValue(), 'ultra'); assert.equal(await custom.isVisible(), false);
      await admin.locator('[data-pc-enabled="8"][data-pc-category="pelican"]').uncheck();
      await admin.locator('[data-pc-edit="8"]').click();
      const modal = admin.locator('#pc-group-dialog');
      assert.equal(await modal.locator('[name="model"]').count(), 0, 'group dialog configures only credentials');
      await modal.locator('[name="key"]').fill(`sk-browser-dedicated-key-8-${layout.name}-123456`);
      await modal.locator('[name="clear_key"]').check();
      await modal.getByRole('button', { name: '应用配置' }).click();
      assert.match(await modal.locator('#pc-group-error').innerText(), /不能同时/);
      await modal.locator('[name="clear_key"]').uncheck();
      await modal.locator('[name="key"]').focus();
      assert(await modal.locator('[name="key"]').evaluate(input => {
        const bounds = input.getBoundingClientRect();
        const footer = input.closest('form').querySelector('footer').getBoundingClientRect();
        const body = input.closest('.pc-modal-body').getBoundingClientRect();
        return bounds.top >= body.top && bounds.bottom <= Math.min(body.bottom, footer.top);
      }), 'key field must remain above footer');
      await fit(admin); await shot(admin, `${layout.name}-admin-key`);
      await modal.getByRole('button', { name: '应用配置' }).click();
      let result = await save(admin);
      assert.equal(result.platforms.find(platform => platform.id === 'openai').params.reasoning_effort, 'ultra');
      assert.equal(result.groups.find(group => group.id === '8').configurations.pelican.enabled, false);
      for (const channel of ['candy', 'pelican', 'testllm']) {
        const value = result.groups.find(group => group.id === '8').configurations[channel];
        assert(value.key_configured); assert.equal(value.override, null); assert.equal(value.model, `gpt-shared-${layout.name}`);
      }
      assert.equal(new Set(['candy', 'pelican', 'testllm'].map(channel => store.group('8', channel).key_fingerprint)).size, 1);
      assert.equal(store.group('2', 'candy').key_cipher, claudeKey);
      assert.doesNotMatch(JSON.stringify(result), /sk-browser|key_cipher|key_reconfirm_required/);
      assert.equal(await admin.evaluate(() => /sk-browser/.test(JSON.stringify(localStorage) + JSON.stringify(sessionStorage))), false);
      await admin.reload(); await admin.locator('#pc-provider-form').waitFor();
      await admin.locator('[data-pc-view="platforms"]').click();
      await admin.locator('[data-pc-platform="openai"]').click();
      assert.equal(await preset.inputValue(), 'ultra');
      assert.equal(await form.locator('[name="model"]').inputValue(), `gpt-shared-${layout.name}`);
      await admin.locator('[data-pc-edit="8"]').click();
      assert.equal(await modal.locator('[name="key"]').inputValue(), '');
      await admin.locator('#pc-group-cancel').click();
      const retained = ['candy', 'pelican', 'testllm'].map(channel => store.group('8', channel).key_cipher);
      await preset.selectOption('custom'); await custom.fill('');
      assert.equal(await form.evaluate(element => element.checkValidity()), false);
      await custom.fill(`manual-shared-${layout.name}`);
      await form.locator('[name="target_url"]').fill('https://changed-relay.example.com/v1');
      await admin.locator('[data-pc-enabled="8"][data-pc-category="pelican"]').check();
      await admin.locator('[data-pc-view="providers"]').click();
      await admin.locator('[data-pc-site="manxue"] [name="api_url"]').fill('https://changed-manxue.example.com/tests');
      await admin.locator('[data-pc-site="testllm"] [name="api_url"]').fill('https://changed-testllm.example.com');
      result = await save(admin);
      assert.deepEqual(['candy', 'pelican', 'testllm'].map(channel => store.group('8', channel).key_cipher), retained);
      assert(result.groups.find(group => group.id === '8').configurations.pelican.enabled);
      await admin.reload(); await admin.locator('#pc-provider-form').waitFor();
      await admin.locator('[data-pc-view="platforms"]').click();
      await admin.locator('[data-pc-platform="openai"]').click();
      assert.equal(await preset.inputValue(), 'custom'); assert.equal(await custom.inputValue(), `manual-shared-${layout.name}`);
      await fit(admin); await shot(admin, `${layout.name}-admin-chatgpt`);
      const otherBefore = store.counts('2', 'candy').total;
      for (const channel of ['candy', 'pelican', 'testllm']) {
        await admin.locator('#pc-history-channel').selectOption(channel);
        const before = store.counts('8', channel).total;
        const response = admin.waitForResponse(response => response.url().includes(`/api/admin/provider/groups/8/${channel}/runs`) && response.request().method() === 'POST');
        await admin.locator('[data-pc-run="8"]').click();
        const queued = await response; assert.equal(queued.status(), 202);
        const id = (await queued.json()).run.id;
        await admin.waitForFunction(() => document.querySelector('[data-pc-run="8"]').closest('tr').innerText.includes('通过 / 正常'));
        assert.equal(store.counts('8', channel).total, before + 1);
        const snapshot = JSON.parse(store.run(id).snapshot_json);
        assert.equal(snapshot.model, `gpt-shared-${layout.name}`); assert.equal(snapshot.reasoning_effort, `manual-shared-${layout.name}`);
        assert.equal(snapshot.target_url, 'https://changed-relay.example.com/v1');
        assert.equal(snapshot.api_url, channel === 'testllm' ? 'https://changed-testllm.example.com' : 'https://changed-manxue.example.com/tests');
        assert.equal(snapshot.key_cipher, retained[['candy', 'pelican', 'testllm'].indexOf(channel)]);
      }
      await admin.locator('#pc-history-channel').selectOption('candy');
      const batch = admin.waitForResponse(response => response.url().endsWith('/api/admin/provider/candy/runs') && response.request().method() === 'POST');
      await admin.locator('[data-pc-batch]').click();
      const batchResponse = await batch; assert.equal(batchResponse.status(), 202);
      assert.deepEqual(batchResponse.request().postDataJSON(), { platform: 'openai' });
      assert.deepEqual((await batchResponse.json()).runs.map(run => run.group_id), ['8']);
      assert.equal(store.counts('2', 'candy').total, otherBefore);
      await admin.locator('[data-pc-platform="anthropic"]').click();
      await form.locator('[name="model"]').fill(`claude-shared-${layout.name}`);
      await form.locator('[name="target_url"]').fill('https://claude-relay.example.com/v1');
      await preset.selectOption('high');
      result = await save(admin);
      assert.equal(result.platforms.find(platform => platform.id === 'openai').params.reasoning_effort, `manual-shared-${layout.name}`);
      assert.equal(result.platforms.find(platform => platform.id === 'anthropic').params.model, `claude-shared-${layout.name}`);
      assert.equal(result.groups.find(group => group.id === '2').configurations.testllm.model, `claude-shared-${layout.name}`);
      assert.equal(store.group('2', 'candy').key_cipher, claudeKey);
      await fit(admin); await shot(admin, `${layout.name}-admin-claude`);
      await admin.locator('#pc-history-channel').selectOption('testllm');
      await admin.locator('[data-pc-platform="gemini"]').click();
      assert.equal(await admin.locator('#pc-history-channel').inputValue(), 'candy');
      assert.equal(await admin.locator('[data-pc-enabled="40"][data-pc-category="testllm"]').isDisabled(), true);
      await fit(admin); await shot(admin, `${layout.name}-admin-gemini`);
      await admin.locator('[data-pc-view="schedule"]').click();
      await admin.locator('[data-pc-plan="candy"] input[value="interval"]').check();
      await admin.locator('[data-pc-plan="candy"] [name="interval_minutes"]').fill('120');
      result = await save(admin);
      assert.equal(result.channels.candy.schedule.mode, 'interval'); assert.equal(result.channels.candy.schedule.interval_minutes, 120);
      assert.equal(result.channels.pelican.schedule.mode, 'daily'); assert.equal(result.channels.testllm.schedule.mode, 'daily');
      await fit(admin); await shot(admin, `${layout.name}-admin-schedule`);
      await admin.locator('#legacy-config > summary').click();
      await admin.locator('.platform-panel:not([hidden])').waitFor();
      assert.equal(await admin.locator('#save-button').isVisible(), true);
      await adminContext.close();
      assert.equal(preview.outboundCalls, 0); assert.equal(preview.providerCalls, 0);
    }
    const embeddedContext = await browser.newContext({ viewport: { width: 1440, height: 950 }, locale: 'zh-CN' });
    const embedded = await embeddedContext.newPage(); watch(embedded);
    await embedded.goto(menuUrl);
    const detector = embedded.frameLocator('#detector');
    await detector.locator('[data-channel="pelican"]').click();
    await detector.locator('.p-card button[data-group="8"]').last().click();
    await detector.frameLocator('.p-artwork').getByRole('heading', { name: '演示作品' }).waitFor();
    assert.match(await detector.locator('.p-artwork').getAttribute('src'), /signature=/);
    await shot(embedded, 'desktop-embedded-pelican');
    await embeddedContext.close();
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
    assert.equal(preview.outboundCalls, 0); assert.equal(preview.providerCalls, 0);
    console.log(JSON.stringify({ ok: true, layouts: ['1440', '390', '320', 'dark'], errors, external, directory }, null, 2));
  } finally { await browser?.close(); menuServer.closeAllConnections?.(); await new Promise(resolve => menuServer.close(resolve)); await preview.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
